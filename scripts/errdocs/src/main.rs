//! Writes the site's errors page from the runner's catalogue and the
//! parser's diagnostic codes, so an error's code, exit status, hint and
//! documentation live in one table in the code and cannot drift from the
//! page. Run it with `task docs:errors`; the `errors_page_is_current` test
//! fails when the page is stale.

#![forbid(unsafe_code)]

use std::fmt::Write as _;
use std::process::exit;

use apic_gocompat::FlagSet;
use apic_runner::{Code, CATALOGUE};

/// The errors page on the site, relative to the repository root.
const PAGE: &str = "website/src/content/docs/errors.md";

fn main() {
    let mut flags = FlagSet::new("errdocs");
    flags.string("o", PAGE, "the page to write");
    flags.bool(
        "check",
        false,
        "fail if the page is stale instead of writing it",
    );
    flags.parse_env();
    let out = flags.get("o");
    let page = markdown();
    if flags.get_bool("check") {
        let current = match std::fs::read(out) {
            Ok(data) => String::from_utf8_lossy(&data).into_owned(),
            Err(err) => fatal(&apic_gocompat::path_error(
                "open",
                std::path::Path::new(out),
                &err,
            )),
        };
        if current.replace("\r\n", "\n") != page {
            fatal(&format!("{out} is stale; run `task docs:errors`"));
        }
        return;
    }
    if let Err(err) = std::fs::write(out, page) {
        fatal(&apic_gocompat::path_error(
            "open",
            std::path::Path::new(out),
            &err,
        ));
    }
}

fn fatal(msg: &str) -> ! {
    eprintln!("{msg}");
    exit(1);
}

const INTRO: &str = r##"---
title: Errors
description: "The catalogue of error codes apic reports, each with its meaning and what to do next, for scripts and agents that branch on the code."
---

<!-- Generated by scripts/errdocs from crates/runner/src/errors.rs; edit
the catalogue there and run task docs:errors. -->

Every error apic reports carries a stable code. A script or an agent can
branch on the code rather than on the wording of the message, which may
improve from release to release; a code never changes meaning, and new ones
are only added.

The first digit groups them: **E1xx** is the request as written, **E2xx**
the command and the project around it, **E3xx** the network. The exit
status follows from the code: 2 for E1xx and E2xx, 3 for E3xx (see
[exit codes](cli.md#exit-codes)). A failed assertion is not an error: it
exits 1 and is reported in the result.

## Where the code appears

Under the message, with the catalogue's hint when the message does not
already name an apic command to run (dim on a terminal, plain in a log):

```text
error: auth.http:9: missing variable
  {{token}}: pass --var token=... or add it to http-client.env.json
  hint: Pass it with --var name=value, add it to an env file, or run the request that captures it first.
  E101 missing variable · see https://apic.sh/errors/#e101
```

With `--json`, as one object on **stderr** (stdout keeps only results, so a
pipe into `jq` is not disturbed):

```json
{"error":{"code":"E101","title":"missing variable","message":"auth.http:9: missing variable\n  {{token}}: it is captured by request …","hint":"Pass it with --var name=value, …","exit":2,"url":"https://apic.sh/errors/#e101"}}
```

Over [MCP](agents.md), a failed tool call carries the same object as its
structured content, and its text ends with the code, title and hint.

When the error is about a name that matches nothing but is close to one
that exists (a request id, the target of a `# @ref` or an environment, with a
typo, the wrong case or `_` for `-`), the message asks "did you mean" and the object carries
the closest names, best first, under `suggestions`; an agent can retry
with the first rather than listing. The key is absent when nothing is close.

```json
{"error":{"code":"E201","title":"unknown request","message":"no request named \"get-usr\"; did you mean get-user? (run `apic list` for every id)","hint":"Run apic list …","exit":2,"url":"https://apic.sh/errors/#e201","suggestions":["get-user"]}}
```

"##;

const DIAGNOSTICS: &str = r##"
## Validate diagnostics

`apic validate` reports problems in the files before anything runs, each
with a line, a column and one of these codes (the `code` key of
`validate --json`). They are a separate namespace from the E codes above:
a file with an error-severity diagnostic refuses to run with
[E103](#e103).

| Code | Meaning |
|---|---|
"##;

/// The whole page.
fn markdown() -> String {
    let mut b = String::from(INTRO);
    b.push_str("## Summary\n\n| Code | Exit | Title |\n|---|---|---|\n");
    for e in CATALOGUE {
        let _ = writeln!(
            b,
            "| [{}](#{}) | {} | {} |",
            e.code,
            anchor(e.code),
            e.exit,
            e.title
        );
    }
    let mut group = "";
    for e in CATALOGUE {
        let g = group_of(e.code);
        if g != group {
            group = g;
            let _ = write!(b, "\n## {g}\n");
        }
        let _ = write!(
            b,
            "\n<a id=\"{}\"></a>\n\n### {} {}\n\n",
            anchor(e.code),
            e.code,
            e.title
        );
        let _ = writeln!(
            b,
            "Exit {}. {}\n\n**What to do:** {}",
            e.exit, e.about, e.hint
        );
    }
    b.push_str(DIAGNOSTICS);
    let mut codes: Vec<(&str, &str)> = apic_httpfile::CODES.to_vec();
    codes.sort();
    for (name, meaning) in codes {
        let _ = writeln!(b, "| `{name}` | {} |", escape_cell(meaning));
    }
    b
}

fn anchor(c: Code) -> String {
    c.as_str().to_lowercase()
}

fn group_of(c: Code) -> &'static str {
    match c.as_str().as_bytes()[1] {
        b'1' => "E1xx: the request",
        b'2' => "E2xx: the command and project",
        _ => "E3xx: the network",
    }
}

/// Keeps a table cell in one cell: a pipe outside backticks would start a
/// new one.
fn escape_cell(s: &str) -> String {
    let mut b = String::new();
    let mut code = false;
    for r in s.chars() {
        if r == '`' {
            code = !code;
        } else if r == '|' && !code {
            b.push('\\');
        }
        b.push(r);
    }
    b
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Fails when the catalogue changed without `task docs:errors`, which
    /// is how CI catches a stale errors page.
    #[test]
    fn errors_page_is_current() {
        let path = format!("{}/../../{PAGE}", env!("CARGO_MANIFEST_DIR"));
        let current = std::fs::read_to_string(path).expect("the errors page");
        assert!(
            current.replace("\r\n", "\n") == markdown(),
            "docs/errors.md is stale; run `task docs:errors`"
        );
    }

    /// Every code has an anchor that its URL points at, and the page's
    /// example URL is the real one.
    #[test]
    fn anchors() {
        let md = markdown();
        for e in CATALOGUE {
            let url = e.code.url();
            let id = &url[url.find('#').expect("an anchor") + 1..];
            assert!(
                md.contains(&format!("<a id=\"{id}\"></a>")),
                "{}: no anchor {id}",
                e.code
            );
        }
        assert!(
            md.contains(&Code::MissingVariable.url()),
            "the example URL does not match the code's URL"
        );
    }
}
