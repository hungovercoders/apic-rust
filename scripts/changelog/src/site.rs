static MINOR_PREFIX: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(&format!("^{MINOR}")).expect("a valid pattern"));

/// A version's major.minor: 0.2 for 0.2.0 and for 0.2.0-rc.1.
fn minor_of(version: &str) -> &str {
    MINOR_PREFIX.find(version).map_or("", |m| m.as_str())
}

/// Returns a file of the repository by its path from the root: as it is on
/// disk, or as it was at a commit (`from_git`, in release.rs), so the
/// release check can be run against history as well as the working tree.
/// A file that does not exist is [`Error::NotExist`].
pub(crate) type Reader = Box<dyn Fn(&str) -> Result<String, Error>>;

pub(crate) fn from_disk(root: &str) -> Reader {
    let root = root.to_string();
    Box::new(move |path| {
        let full = Path::new(&root).join(path);
        match std::fs::read(&full) {
            Ok(data) => Ok(String::from_utf8_lossy(&data).into_owned()),
            Err(err) => {
                let msg = path_error("open", &full, &err);
                if err.kind() == std::io::ErrorKind::NotFound {
                    Err(Error::NotExist(msg))
                } else {
                    Err(Error::Other(msg))
                }
            }
        }
    })
}

/// Returns a file's text as it is, and with every pin in it naming
/// `version`.
pub(crate) fn pinned(
    read: &Reader,
    pins: &[Pin],
    file: &str,
    version: &str,
) -> Result<(String, String), Error> {
    let before = read(file)?;
    let mut after = before.clone();
    for p in pins.iter().filter(|p| p.file == file) {
        if !p.re.is_match(&after) {
            return Err(Error::Other(format!(
                "{file}: no match for the pin {}; reword it in PINS (scripts/changelog/src/site.rs) rather than in the page",
                quote(&p.text)
            )));
        }
        let text = p
            .text
            .replace("{v}", version)
            .replace("{minor}", minor_of(version));
        after = p.re.replace_all(&after, NoExpand(&text)).into_owned();
    }
    Ok((before, after))
}

/// Every file the site's changelog and the pins touch, the page first,
/// each once.
fn files(pins: &[Pin]) -> Vec<String> {
    let mut out = vec![PAGE.to_string()];
    for p in pins {
        if !out.contains(&p.file) {
            out.push(p.file.clone());
        }
    }
    out
}

/// One file as it is and as the changelog says it should be.
pub(crate) struct Change {
    pub file: String,
    pub current: String,
    pub want: String,
}

/// Returns every file the changelog governs with what it should hold for
/// the published release: the site's page, and each pinned page naming the
/// newest stable release at or below it.
fn changes(read: &Reader, pins: &[Pin], changelog: &str) -> Result<Vec<Change>, Error> {
    let published = published(read, changelog)?;
    let stable = stable(changelog, &published)?;
    let mut out = Vec::new();
    for file in files(pins) {
        if file == PAGE {
            let current = match read(PAGE) {
                Ok(text) => text,
                Err(Error::NotExist(_)) => String::new(),
                Err(err) => return Err(err),
            };
            out.push(Change {
                file,
                current,
                want: site_page(changelog, &published),
            });
            continue;
        }
        let (before, after) = pinned(read, pins, &file, &stable)?;
        out.push(Change {
            file,
            current: before,
            want: after,
        });
    }
    Ok(out)
}

/// Lists the files that do not match the changelog yet.
pub(crate) fn stale(read: &Reader, pins: &[Pin], changelog: &str) -> Result<Vec<String>, Error> {
    Ok(changes(read, pins, changelog)?
        .into_iter()
        .filter(|c| c.current != c.want)
        .map(|c| c.file)
        .collect())
}

/// Records `version` as published and brings the docs in line: what
/// release.yml's docs job runs once a release is out. `version` needs a
/// dated section, and a release older than the one recorded is refused,
/// since the docs would then name an older release than the newest one
/// out.
pub(crate) fn publish(
    root: &str,
    pins: &[Pin],
    changelog: &str,
    version: &str,
) -> Result<(), Error> {
    if version == UNRELEASED {
        return Err(Error::Other(
            "the Unreleased section is not a release".to_string(),
        ));
    }
    latest(changelog)?;
    section(changelog, version)?;
    let disk = from_disk(root);
    if let Ok(current) = published(&disk, changelog) {
        if compare_versions(version, &current).is_lt() {
            return Err(Error::Other(format!(
                "{RELEASED} records {current} already; {version} is older"
            )));
        }
    }
    // Regenerate against the new record first and write nothing unless
    // that succeeds, so a pin that no longer matches leaves the files as
    // they were rather than half moved.
    let record = format!("{version}\n");
    let next: Reader = {
        let (disk, record) = (from_disk(root), record.clone());
        Box::new(move |path| {
            if path == RELEASED {
                Ok(record.clone())
            } else {
                disk(path)
            }
        })
    };
    let mut all = changes(&next, pins, changelog)?;
    let current = match disk(RELEASED) {
        Ok(text) => text,
        Err(Error::NotExist(_)) => String::new(),
        Err(err) => return Err(err),
    };
    all.push(Change {
        file: RELEASED.to_string(),
        current,
        want: record,
    });
    write_changes(root, &all)
}

/// Brings the site's changelog page and every pin in line with the
/// changelog and the published release, leaving a file that already
/// matches untouched.
pub(crate) fn write(root: &str, pins: &[Pin], changelog: &str) -> Result<(), Error> {
    let all = changes(&from_disk(root), pins, changelog)?;
    write_changes(root, &all)
}

/// Writes each change whose file does not already hold it.
fn write_changes(root: &str, all: &[Change]) -> Result<(), Error> {
    for c in all {
        if c.current == c.want {
            continue;
        }
        let path = Path::new(root).join(&c.file);
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir)
                .map_err(|err| Error::Other(path_error("mkdir", dir, &err)))?;
        }
        std::fs::write(&path, &c.want)
            .map_err(|err| Error::Other(path_error("open", &path, &err)))?;
        println!("wrote {}", c.file);
    }
    Ok(())
}
