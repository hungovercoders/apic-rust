//! The site's side of a release: the changelog page, the places the docs
//! pin a version, and the record of the newest published release.

use std::collections::HashSet;
use std::path::Path;
use std::sync::LazyLock;

use apic_gocompat::{path_error, quote};
use regex::{NoExpand, Regex};

use crate::scan::scan;
use crate::{compare_versions, latest, section, stable, Error, SEMVER, UNRELEASED};

/// The site's changelog page, relative to the repository root.
pub(crate) const PAGE: &str = "website/src/content/docs/changelog.md";

const PAGE_HEAD: &str = r#"---
title: Changelog
description: "What changed in each apic release: new commands, flags and MCP tools, changes to the --json contract, and fixes, newest first."
---

<!-- Generated by scripts/changelog from CHANGELOG.md at the repository
root; edit that file and run task docs:changelog. -->

"#;

/// Three or more newlines, which the page folds into one blank line where
/// a section was taken out.
static BLANK_RUNS: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"\n{3,}").expect("a valid pattern"));

/// Names the newest published release, the one the site's page and pins
/// follow. A release pull request dates its section and leaves this alone,
/// so the site does not name a version before its archives exist;
/// release.yml's docs job moves it with -publish once the release has
/// published, and commits what that regenerates.
pub(crate) const RELEASED: &str = "website/released-version";

/// Reads [`RELEASED`]: a version with a dated section in `changelog`.
fn published(read: &Reader, changelog: &str) -> Result<String, Error> {
    let text = read(RELEASED)?;
    let v = text.trim();
    if !SEMVER.is_match(v) {
        return Err(Error::Other(format!(
            "{RELEASED} holds {}, not a version like 0.2.0",
            quote(v)
        )));
    }
    if let Err(err) = section(changelog, v) {
        return Err(Error::Other(format!("{RELEASED} names {v}: {err}")));
    }
    Ok(v.to_string())
}

/// Renders CHANGELOG.md as the site's page for the published release: the
/// file's own title gives way to the page's front matter, and Unreleased
/// and every section above `published` are left out with their link
/// references. The page lists releases a reader can install, so neither a
/// line under Unreleased nor a release pull request's newly dated section
/// changes it; publishing does.
pub(crate) fn site_page(changelog: &str, published: &str) -> String {
    let mut text = changelog;
    if text.starts_with("# ") {
        text = text.split_once('\n').map_or("", |(_, rest)| rest);
    }
    let lines = scan(text);
    let mut hidden: HashSet<&str> = HashSet::new();
    for l in &lines {
        if let Some(h) = &l.heading {
            if h.from == UNRELEASED || compare_versions(h.version(), published).is_gt() {
                hidden.insert(&h.from);
                hidden.insert(&h.to);
            }
        }
    }
    let mut kept: Vec<&str> = Vec::new();
    let mut skipping = false;
    for l in &lines {
        if l.h2 || l.trailing {
            skipping = l
                .heading
                .as_ref()
                .is_some_and(|h| hidden.contains(h.from.as_str()));
        }
        if skipping
            || l.reference
                .as_ref()
                .is_some_and(|r| hidden.contains(r.as_str()))
        {
            continue;
        }
        kept.push(&l.text);
    }
    let joined = kept.join("\n");
    let folded = BLANK_RUNS.replace_all(&joined, "\n\n");
    format!("{PAGE_HEAD}{}\n", folded.trim())
}

/// One place the docs name the current release: the phrase as it reads,
/// with `{v}` for the version (0.2.0) and `{minor}` for its minor (0.2).
/// The phrase is matched with any version in those places and the rest
/// taken literally, so a dot in a hostname is a dot. Every pin must match
/// at least once, so a reworded line fails the test instead of keeping an
/// old version quietly.
#[derive(Clone, Debug)]
pub(crate) struct Pin {
    /// Relative to the repository root.
    pub file: String,
    /// The phrase, with `{v}` and `{minor}`.
    pub text: String,
    pub re: Regex,
}

/// Patterns for a version in a pin: a full version, prerelease included so
/// a pin rewritten from one cannot keep its suffix, and a minor. `SEMVER`
/// in main.rs is the same grammar, anchored.
pub(crate) const VER: &str = r"[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?";
const MINOR: &str = r"[0-9]+\.[0-9]+";

static PLACEHOLDER: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"\{v\}|\{minor\}").expect("a valid pattern"));

pub(crate) fn pin(file: &str, text: &str) -> Pin {
    let mut pattern = String::new();
    let mut last = 0;
    for m in PLACEHOLDER.find_iter(text) {
        pattern.push_str(&regex::escape(&text[last..m.start()]));
        pattern.push_str(if m.as_str() == "{v}" { VER } else { MINOR });
        last = m.end();
    }
    pattern.push_str(&regex::escape(&text[last..]));
    Pin {
        file: file.to_string(),
        text: text.to_string(),
        re: Regex::new(&pattern).expect("a valid pattern"),
    }
}

