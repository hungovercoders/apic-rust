//! The keywords of every Gherkin dialect, selected by a `# language:`
//! header. `steps` holds the step keywords of all five kinds, longest
//! spelling first, which is the order the matcher tries them in.

/// One language's keywords.
pub(super) struct Dialect {
    pub(super) language: &'static str,
    pub(super) feature: &'static [&'static str],
    pub(super) rule: &'static [&'static str],
    pub(super) background: &'static [&'static str],
    pub(super) scenario: &'static [&'static str],
    pub(super) scenario_outline: &'static [&'static str],
    pub(super) examples: &'static [&'static str],
    pub(super) steps: &'static [&'static str],
}

/// The dialect for a language code such as `en` or `fr`.
pub(super) fn dialect(language: &str) -> Option<&'static Dialect> {
    DIALECTS.iter().find(|d| d.language == language)
}

