//! The importer end to end: a collection in, a project out, read back
//! through the project loader.

use std::collections::{BTreeMap, HashMap, HashSet};
use std::fs;

use apic_postman::{import, looks_like_collection, looks_like_environment, ImportResult, Options};
use tempfile::TempDir;

const COLLECTION: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/testdata/collection.json");
const STAGING: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/testdata/staging.postman_environment.json"
);

fn must_read(path: &str) -> String {
    fs::read_to_string(path).unwrap()
}

#[track_caller]
fn has(text: &str, wants: &[&str]) {
    for w in wants {
        assert!(text.contains(w), "missing {w:?} in:\n{text}");
    }
}

fn opts(out_dir: &str) -> Options {
    Options {
        out_dir: out_dir.to_string(),
        ..Options::default()
    }
}

fn dir_path(dir: &TempDir, parts: &[&str]) -> String {
    let mut p = dir.path().to_path_buf();
    for part in parts {
        p.push(part);
    }
    p.to_string_lossy().into_owned()
}

fn write(dir: &TempDir, name: &str, text: &str) -> String {
    let p = dir_path(dir, &[name]);
    fs::write(&p, text).unwrap();
    p
}

type Envs = BTreeMap<String, BTreeMap<String, String>>;

fn value<'a>(envs: &'a Envs, env: &str, key: &str) -> &'a str {
    envs.get(env)
        .and_then(|vars| vars.get(key))
        .map_or("", String::as_str)
}

#[test]
fn import_collection() {
    let dir = TempDir::new().unwrap();
    let out = dir_path(&dir, &[]);
    let res = import(
        COLLECTION,
        Options {
            out_dir: out.clone(),
            env_files: vec![STAGING.to_string()],
            force: false,
        },
    )
    .unwrap();
    assert_eq!(res.requests, 14);
    let names: HashSet<String> = res
        .files
        .iter()
        .map(|f| apic_project::path::base(f))
        .collect();
    for want in [
        "auth.http",
        "todos.http",
        "todos-archive.http",
        "todo-api.http",
        "todo-api.tricky-body.body.txt",
        "http-client.env.json",
        "http-client.private.env.json",
        "apic.yaml",
    ] {
        assert!(
            names.contains(want),
            "{want} not written; files = {:?}",
            res.files
        );
    }
    assert!(
        res.base_url == "https://api.example.com"
            && !res.env_file.is_empty()
            && !res.private_env_file.is_empty(),
        "result = {res:?}"
    );

    let auth = must_read(&format!("{out}/auth.http"));
    has(&auth, &[
        "# auth — generated by `apic import` from \"collection.json\". Edit freely.\n",
        "\n### Log in\n# @name log-in\n# @description Exchange credentials for a token.\n# @auth none\n# @capture token = body.$.access_token\n# @assert status == 200\n# @assert body.$.access_token exists\n# @assert body.$.user.name == alice\n# @assert header.content-type contains json\nPOST {{baseUrl}}/auth/login\nContent-Type: application/json\n# X-Debug: 1  (disabled)\n\n{\"user\": \"{{user}}\", \"password\": \"{{password}}\"}\n",
        "\n### Who am I\n# @name who-am-i\n# @assert status == 200\n# @assert header.x-request-id exists\n# @assert duration < 500\nGET {{baseUrl}}/me\n",
    ]);
    assert!(
        !auth.contains("# @auth bearer"),
        "the collection auth is the project default, not repeated per request"
    );

    let todos = must_read(&format!("{out}/todos.http"));
    has(&todos, &[
        "@id = 42\n",
        "\n### List todos\n# @name list-todos\n# @assert body.$.items[0].id exists\nGET {{baseUrl}}/todos?done=true&limit={{pageSize}}\n    # &cursor=abc  (disabled)\nX-Api-Key: {{apiKey}}\n",
        "\n### Get todo\n# @name get-todo\nGET {{baseUrl}}/todos/{{id}}\nX-Api-Key: {{apiKey}}\n",
        "\n### Get todo\n# @name get-todo-2\nGET {{baseUrl}}/todos/{{$uuid}}\n",
    ]);

    let archive = must_read(&format!("{out}/todos-archive.http"));
    has(&archive, &[
        "POST {{baseUrl}}/todos/{{id}}/attachments\nContent-Type: multipart/form-data; boundary=WebAppBoundary\nX-Api-Key: {{apiKey}}\n\n--WebAppBoundary\nContent-Disposition: form-data; name=\"title\"\n\nQuarterly\n--WebAppBoundary\nContent-Disposition: form-data; name=\"file\"; filename=\"report.pdf\"\nContent-Type: application/pdf\n\n< ./report.pdf\n--WebAppBoundary--\n",
        "POST {{baseUrl}}/todos/search\nContent-Type: application/x-www-form-urlencoded\nX-Api-Key: {{apiKey}}\n\nq=a+b%26c&owner={{user}}\n",
        "POST {{baseUrl}}/graphql\nContent-Type: application/json\nX-Api-Key: {{apiKey}}\n\n{\"query\":\"query Todos($done: Boolean) { todos(done: $done) { id } }\",\"variables\":{\"done\":true}}\n",
        "PUT {{baseUrl}}/todos/import\nX-Api-Key: {{apiKey}}\n\n< ./todos.csv\n",
    ]);

    let root = must_read(&format!("{out}/todo-api.http"));
    has(&root, &[
        "# @auth aws region=eu-west-2 service=execute-api\n",
        "# @auth oauth2 tokenUrl={{tokenUrl}} clientId={{clientId}} clientSecret={{clientSecret}} scope=\"read write\" clientAuth=basic\n",
        "# @auth basic alice \"s3cret pass\"\n",
        "\n### Digest\n# @name digest\n# @auth digest alice {{password}}\nGET {{baseUrl}}/digest\n",
        "\n### Tricky ### body\n# @name tricky-body\nPOST {{baseUrl}}/notes\nContent-Type: text/plain\n\n< ./todo-api.tricky-body.body.txt\n",
    ]);
    assert_eq!(
        must_read(&format!("{out}/todo-api.tricky-body.body.txt")),
        "### heading\nbody text"
    );

    let env: Envs = serde_json::from_str(&must_read(&res.env_file)).unwrap();
    assert!(
        value(&env, "$shared", "baseUrl") == "https://api.example.com"
            && value(&env, "$shared", "pageSize") == "20"
            && value(&env, "$shared", "unused").is_empty(),
        "shared = {:?}",
        env.get("$shared")
    );
    assert!(
        value(&env, "staging-eu", "baseUrl") == "https://staging.example.com"
            && value(&env, "staging-eu", "user") == "alice"
            && value(&env, "staging-eu", "password").is_empty()
            && value(&env, "staging-eu", "old").is_empty(),
        "staging = {:?}",
        env.get("staging-eu")
    );
    let private: Envs = serde_json::from_str(&must_read(&res.private_env_file)).unwrap();
    assert!(
        value(&private, "staging-eu", "password") == "s3cret" && private.len() == 1,
        "private = {private:?}"
    );
    // File modes are not meaningful on Windows.
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt as _;
        let mode = fs::metadata(&res.private_env_file)
            .unwrap()
            .permissions()
            .mode();
        assert_eq!(mode & 0o777, 0o600, "private env file mode");
    }
    has(
        &must_read(&format!("{out}/apic.yaml")),
        &[
            "env: staging-eu\n",
            "auth:\n  default: \"bearer {{token}}\"\n",
        ],
    );

    // What could not be carried over is reported, by request.
    let got: HashMap<String, &str> = res
        .unsupported
        .iter()
        .map(|u| (format!("{}|{}", u.request, u.what), u.reason.as_str()))
        .collect();
    for key in [
        "log-in|pm.expect(jsonData.roles).to.be.an('array');",
        "who-am-i|pre-request script",
        "upload-attachment|file part file",
        "raw-file-body|body file",
    ] {
        assert!(
            got.contains_key(key),
            "unsupported {key:?} not reported; got {got:?}"
        );
    }
    assert_eq!(
        res.unsupported.len(),
        4,
        "unsupported = {:?}",
        res.unsupported
    );

    // The generated project parses and validates as written, part files
    // aside, which the notes point at.
    for f in ["report.pdf", "todos.csv"] {
        fs::write(format!("{out}/{f}"), "x").unwrap();
    }
    let p = apic_project::load(&out).unwrap();
    for d in p.validate() {
        assert!(d.severity != "error", "validate: {d}");
    }
    assert_eq!(p.requests().len(), 14);

    // A second run keeps what exists.
    let res2 = import(COLLECTION, opts(&out)).unwrap();
    assert!(
        res2.files.is_empty() && res2.skipped.len() >= 6 && res2.requests == 14,
        "second run: files={:?} skipped={:?} requests={}",
        res2.files,
        res2.skipped,
        res2.requests
    );
}

#[test]
fn import_refuses_v1_and_non_collections() {
    let dir = TempDir::new().unwrap();
    let out = dir_path(&dir, &[]);
    let v1 = write(
        &dir,
        "v1.json",
        r#"{"id": "x", "name": "old", "order": [], "requests": [], "info": {"schema": "https://schema.getpostman.com/json/collection/v1.0.0/"}}"#,
    );
    let err = import(&v1, opts(&out)).unwrap_err();
    assert!(err.to_string().contains("v1"), "v1: {err}");
    let not_one = write(&dir, "openapi.json", r#"{"openapi": "3.0.0", "paths": {}}"#);
    assert!(
        import(&not_one, opts(&out)).is_err(),
        "an OpenAPI document is not a collection"
    );
    assert!(
        looks_like_collection(
            br#"{"info": {"schema": "https://schema.getpostman.com/json/collection/v2.1.0/collection.json"}, "item": []}"#
        ) && !looks_like_collection(br#"{"openapi": "3.1.0"}"#),
        "collection detection"
    );
    assert!(
        looks_like_environment(
            br#"{"name": "x", "values": [], "_postman_variable_scope": "environment"}"#
        ) && !looks_like_environment(br#"{"item": []}"#),
        "environment detection"
    );
    let env = write(&dir, "env.json", r#"{"nope": true}"#);
    let col = write(
        &dir,
        "c.json",
        r#"{"info": {"name": "c", "schema": "https://schema.getpostman.com/json/collection/v2.0.0/collection.json"}, "item": [{"name": "ping", "request": "https://x/ping"}]}"#,
    );
    let err = import(
        &col,
        Options {
            out_dir: out.clone(),
            env_files: vec![env],
            force: false,
        },
    )
    .unwrap_err();
    assert!(
        err.to_string().contains("not a Postman environment"),
        "bad env file: {err}"
    );
    let res = import(&col, opts(&dir_path(&dir, &["out"]))).unwrap();
    assert_eq!(res.requests, 1, "v2.0 with a string request: {res:?}");
    has(
        &must_read(&dir_path(&dir, &["out", "c.http"])),
        &["\n### ping\n# @name ping\nGET https://x/ping\n"],
    );
    assert!(res.env_file.is_empty(), "no variables, no env file");
}

#[test]
fn import_base_url_skips_empty_shared_variables() {
    let dir = TempDir::new().unwrap();
    let col = write(
        &dir,
        "c.json",
        r#"{"info": {"name": "c", "schema": "https://schema.getpostman.com/json/collection/v2.1.0/collection.json"},
		"item": [{"name": "ping", "request": "{{url}}/ping"}],
		"variable": [{"key": "baseUrl", "value": ""}, {"key": "url", "value": "https://api.example.com"}]}"#,
    );
    let res = import(&col, opts(&dir_path(&dir, &[]))).unwrap();
    assert_eq!(
        res.base_url, "https://api.example.com",
        "an empty baseUrl should fall through to url"
    );
}

#[test]
fn import_api_key_in_query_opens_the_query_string() {
    let dir = TempDir::new().unwrap();
    let col = write(
        &dir,
        "c.json",
        r#"{"info": {"name": "c", "schema": "https://schema.getpostman.com/json/collection/v2.1.0/collection.json"},
"auth": {"type": "apikey", "apikey": [{"key": "in", "value": "query"}, {"key": "key", "value": "api_key"}, {"key": "value", "value": "{{apiKey}}"}]},
"item": [{"name": "users", "request": "https://x/users"}, {"name": "search", "request": "https://x/search?q=1"},
{"name": "upload", "request": {"method": "POST", "url": "https://x/up", "body": {"mode": "formdata", "formdata": [{"key": "cv", "type": "file", "src": "résumé.pdf"}]}}}]}"#,
    );
    let out = dir_path(&dir, &["out"]);
    import(&col, opts(&out)).unwrap();
    let got = must_read(&dir_path(&dir, &["out", "c.http"]));
    has(
        &got,
        &[
            "GET https://x/users\n    ?api_key={{apiKey}}\n",
            "GET https://x/search?q=1\n    &api_key={{apiKey}}\n",
            "Content-Disposition: form-data; name=\"cv\"; filename=\"résumé.pdf\"\n",
        ],
    );
    let p = apic_project::load(&out).unwrap();
    assert_eq!(p.requests()[0].url, "https://x/users?api_key={{apiKey}}");
    let m = p.requests()[2].multipart().unwrap().unwrap();
    assert_eq!(
        m.parts[0].filename, "résumé.pdf",
        "non-ASCII filename round trip: {m:?}"
    );
}

/// The JSON of a result is part of `apic import --json`.
#[test]
fn result_json_shape() {
    assert_eq!(
        serde_json::to_string(&ImportResult::default()).unwrap(),
        r#"{"files":null,"requests":0}"#
    );
    let res = ImportResult {
        files: vec!["a.http".to_string()],
        requests: 1,
        base_url: "https://api".to_string(),
        env_file: "e.json".to_string(),
        private_env_file: "p.json".to_string(),
        skipped: vec!["b.http".to_string()],
        unsupported: vec![apic_postman::Unsupported {
            request: "r".to_string(),
            what: "w".to_string(),
            reason: "why".to_string(),
        }],
    };
    assert_eq!(
        serde_json::to_string(&res).unwrap(),
        r#"{"files":["a.http"],"requests":1,"base_url":"https://api","env_file":"e.json","private_env_file":"p.json","skipped":["b.http"],"unsupported":[{"request":"r","what":"w","reason":"why"}]}"#
    );
}
